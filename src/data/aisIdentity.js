/**
 * The MID inside a 9-digit MMSI, by ITU-R M.585 numbering: ships (MIDxxxxxx),
 * handhelds (8MIDxxxxx), group calls (0MIDxxxxx), coast stations
 * (00MIDxxxx), SAR aircraft (111MIDxxx), craft tied to a parent ship
 * (98MIDxxxx) and aids to navigation (99MIDxxxx). SART, MOB and EPIRB
 * devices (970/972/974…) carry no MID. Empty when there is none.
 */
export function midFromMmsi(mmsi) {
  const digits = String(mmsi ?? '').trim();
  if (!/^\d{9}$/.test(digits)) return '';
  let mid;
  if (digits.startsWith('111')) mid = digits.slice(3, 6);
  else if (digits.startsWith('00')) mid = digits.slice(2, 5);
  else if (/^9[89]/.test(digits)) mid = digits.slice(2, 5);
  else if (/^[08]/.test(digits)) mid = digits.slice(1, 4);
  else if (/^[2-7]/.test(digits)) mid = digits.slice(0, 3);
  else return '';
  return /^[2-7]\d\d$/.test(mid) ? mid : '';
}

/**
 * `{ mid, country, countryCode }` for an MMSI, or null when it carries no
 * MID. An assigned-looking MID missing from the table keeps its digits so
 * fleets can still be grouped.
 */
export function flagStateFromMmsi(mmsi) {
  const mid = midFromMmsi(mmsi);
  if (!mid) return null;
  const [country, countryCode] = MID_FLAG[mid] || [`MID ${mid}`, ''];
  return { mid, country, countryCode };
}

/** Short label for cards: `UNITED KINGDOM (GB)`, `MID 799`, or ''. */
export function flagStateLabel(mmsi) {
  const flag = flagStateFromMmsi(mmsi);
  if (!flag) return '';
  return flag.countryCode
    ? `${flag.country} (${flag.countryCode})`
    : flag.country;
}
